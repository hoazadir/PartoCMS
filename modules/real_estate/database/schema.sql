CREATE TABLE IF NOT EXISTS real_estate_properties (
    id INT(11) AUTO_INCREMENT PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    slug VARCHAR(255) NOT NULL UNIQUE,
    description LONGTEXT DEFAULT NULL,
    property_type ENUM('apartment', 'villa', 'land', 'commercial', 'office', 'shop') DEFAULT 'apartment',
    listing_type ENUM('sale', 'rent', 'mortgage') DEFAULT 'sale',
    price DECIMAL(15,2) DEFAULT NULL,
    rent_price DECIMAL(15,2) DEFAULT NULL,
    deposit_price DECIMAL(15,2) DEFAULT NULL,
    area INT(11) DEFAULT NULL,
    rooms INT(11) DEFAULT NULL,
    bathrooms INT(11) DEFAULT NULL,
    year_built INT(4) DEFAULT NULL,
    address VARCHAR(500) DEFAULT NULL,
    city VARCHAR(100) DEFAULT NULL,
    region VARCHAR(100) DEFAULT NULL,
    latitude DECIMAL(10,7) DEFAULT NULL,
    longitude DECIMAL(10,7) DEFAULT NULL,
    featured_image VARCHAR(500) DEFAULT NULL,
    gallery LONGTEXT DEFAULT NULL,
    features LONGTEXT DEFAULT NULL,
    agent_name VARCHAR(150) DEFAULT NULL,
    agent_phone VARCHAR(20) DEFAULT NULL,
    agent_email VARCHAR(150) DEFAULT NULL,
    status ENUM('draft', 'published', 'sold', 'rented') DEFAULT 'published',
    is_featured TINYINT(1) DEFAULT 0,
    sort_order INT(11) DEFAULT 0,
    language VARCHAR(10) DEFAULT 'fa-IR',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX idx_property_type (property_type),
    INDEX idx_listing_type (listing_type),
    INDEX idx_city (city),
    INDEX idx_status (status),
    INDEX idx_featured (is_featured),
    INDEX idx_language (language)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
